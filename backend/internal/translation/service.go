package translation

import (
	"context"
	"encoding/json"
	"errors"
	"fmt"

	"enjoysa-backend/internal/ai/translate"

	"gorm.io/gorm"
)

// ProductFieldUpdater is implemented by a product store; we use a narrow
// interface here so the translation package does not import the product
// package directly (avoiding a cycle). UpdateTranslatedFieldsForDirection
// routes ZH→EN writes to *_en columns and EN→ZH writes to *_zh columns.
type ProductFieldUpdater interface {
	UpdateTranslatedFields(productID uint, fields map[string]string) error
	UpdateTranslatedFieldsForDirection(productID uint, direction string, fields map[string]string) error
}

// ProductTranslationGate decides whether a ZH→EN enqueue should proceed.
// Implemented by the product store; ZH→EN enqueue skips when admin has
// flipped manual_override_en=true on the product.
type ProductTranslationGate interface {
	GetTranslationFlags(productID uint) (manualOverride bool, autoGenerated bool, err error)
}

// ErrManualOverrideEn is returned by ZH→EN enqueue helpers when admin has
// locked the EN side of the product. Caller treats this as a no-op, not a
// failure.
var ErrManualOverrideEn = errors.New("translation: product en side is manually overridden")

// Service is the high-level façade other packages call.
type Service struct {
	store      *Store
	translator *translate.Translator
	products   ProductFieldUpdater
	gate       ProductTranslationGate
}

func NewService(store *Store, tr *translate.Translator, products ProductFieldUpdater) *Service {
	return &Service{store: store, translator: tr, products: products}
}

// SetProductGate wires the manual_override_en gate for ZH→EN enqueue.
// Optional — when unset, ZH→EN enqueue trusts the caller's intent.
func (s *Service) SetProductGate(g ProductTranslationGate) {
	s.gate = g
}

func (s *Service) Store() *Store {
	return s.store
}

// EnqueueProductTranslationInTx writes a pending EN→ZH task that the worker
// will later pick up. Caller passes their own transaction so the task is
// created in the same commit as the product status change.
func (s *Service) EnqueueProductTranslationInTx(tx *gorm.DB, productID uint, enqueuedBy uint, fields map[string]string) (*TranslationTask, error) {
	return s.enqueueInTx(tx, DirectionEN2ZH, productID, enqueuedBy, fields)
}

// EnqueueProductZhToEnInTx is the ZH→EN counterpart introduced for
// REQ-20260509-0004 (admin Chinese-input → AI English). Skips with
// ErrManualOverrideEn if the product has manual_override_en=true.
func (s *Service) EnqueueProductZhToEnInTx(tx *gorm.DB, productID uint, enqueuedBy uint, fields map[string]string) (*TranslationTask, error) {
	if s.gate != nil {
		manualOverride, _, err := s.gate.GetTranslationFlags(productID)
		if err != nil {
			return nil, fmt.Errorf("translation gate: %w", err)
		}
		if manualOverride {
			return nil, ErrManualOverrideEn
		}
	}
	return s.enqueueInTx(tx, DirectionZH2EN, productID, enqueuedBy, fields)
}

func (s *Service) enqueueInTx(tx *gorm.DB, direction Direction, productID uint, enqueuedBy uint, fields map[string]string) (*TranslationTask, error) {
	input, err := json.Marshal(fields)
	if err != nil {
		return nil, err
	}
	task := &TranslationTask{
		TargetType:  TargetTypeProduct,
		TargetID:    productID,
		Direction:   direction,
		Status:      StatusPending,
		MaxRetries:  2,
		FieldsInput: input,
		EnqueuedBy:  enqueuedBy,
	}
	if err := s.store.CreateInTx(tx, task); err != nil {
		return nil, err
	}
	return task, nil
}

// ProcessOne pulls one pending task, runs the LLM, and writes back results.
// Returns false if no work was available. Used by the worker loop.
func (s *Service) ProcessOne(ctx context.Context) (bool, error) {
	task, err := s.store.ClaimNextPending()
	if err != nil {
		return false, err
	}
	if task == nil {
		return false, nil
	}

	var fields map[string]string
	if err := json.Unmarshal(task.FieldsInput, &fields); err != nil {
		_ = s.store.MarkFailedOrRetry(task.ID, "decode fields_input: "+err.Error())
		return true, err
	}

	dir := translate.EN2ZH
	if task.Direction == DirectionZH2EN {
		dir = translate.ZH2EN
	}
	resp, err := s.translator.Translate(ctx, translate.Request{Direction: dir, Fields: fields})
	if err != nil {
		_ = s.store.MarkFailedOrRetry(task.ID, err.Error())
		return true, err
	}

	output, _ := json.Marshal(resp.Translations)

	// Write the translated values back to the product before flipping the
	// task to success, so consumers polling status see the preview as soon as
	// the task reaches success. Direction-aware so ZH→EN writes hit *_en.
	if task.TargetType == TargetTypeProduct && s.products != nil {
		if err := s.products.UpdateTranslatedFieldsForDirection(task.TargetID, string(task.Direction), resp.Translations); err != nil {
			_ = s.store.MarkFailedOrRetry(task.ID, "persist translation: "+err.Error())
			return true, err
		}
	}

	if err := s.store.MarkSuccess(task.ID, output, resp.PromptTokens, resp.CompletionTokens, resp.CostUSD, resp.Provider, resp.ModelVersion); err != nil {
		return true, err
	}
	return true, nil
}

// RetryFailed exposed at service level for handler use.
func (s *Service) RetryFailed(taskID uint) error {
	return s.store.RetryFailed(taskID)
}

// GetLatestForProductByDirection returns the most recent translation task
// for a product in the requested direction, or nil if none exists. Lets the
// admin status endpoint scope its lookup to ZH→EN even if a supplier has
// also queued an EN→ZH task on the same product.
func (s *Service) GetLatestForProductByDirection(productID uint, direction string) (*TranslationTask, error) {
	return s.store.GetLatestForTargetAndDirection(TargetTypeProduct, productID, Direction(direction))
}
