// p is a shorthand constructor to reduce verbosity.
func p(
	nameZh, nameEn string, supIdx int, region, category string,
	status productmodel.ProductStatus, price float64, featured bool,
	sumZh, sumEn, descZh, descEn, addrZh, addrEn, dur, grp, tags string,
	pkg1Zh, pkg1En, pkg1dZh, pkg1dEn string, pkg1P float64,
	pkg2Zh, pkg2En, pkg2dZh, pkg2dEn string, pkg2P float64,
	hl1tZh, hl1tEn, hl1dZh, hl1dEn string,
	hl2tZh, hl2tEn, hl2dZh, hl2dEn string,
	faq1qZh, faq1qEn, faq1aZh, faq1aEn string,
	faq2qZh, faq2qEn, faq2aZh, faq2aEn string,
) productDef {
	return productDef{
		nameZh: nameZh, nameEn: nameEn, supplierIdx: supIdx,
		regionSlug: region, categorySlug: category,
		status: status, priceFrom: price, isFeatured: featured,
		summaryZh: sumZh, summaryEn: sumEn,
		descZh: descZh, descEn: descEn,
		addressZh: addrZh, addressEn: addrEn,
		duration: dur, groupSize: grp, tags: tags,
		pkgNames:  [2][2]string{{pkg1Zh, pkg1En}, {pkg2Zh, pkg2En}},
		pkgDescs:  [2][2]string{{pkg1dZh, pkg1dEn}, {pkg2dZh, pkg2dEn}},
		pkgPrices: [2]float64{pkg1P, pkg2P},
		hlTitles:  [2][2]string{{hl1tZh, hl1tEn}, {hl2tZh, hl2tEn}},
		hlDescs:   [2][2]string{{hl1dZh, hl1dEn}, {hl2dZh, hl2dEn}},
		faqQ:      [2][2]string{{faq1qZh, faq1qEn}, {faq2qZh, faq2qEn}},
		faqA:      [2][2]string{{faq1aZh, faq1aEn}, {faq2aZh, faq2aEn}},
	}
}

