package model

import (
	"time"

	"enjoysa-backend/internal/models"
	"gorm.io/datatypes"
	"gorm.io/gorm"
)

// ProductStatus 产品状态
type ProductStatus string

const (
	ProductStatusDraft    ProductStatus = "draft"
	ProductStatusPending  ProductStatus = "pending"
	ProductStatusApproved ProductStatus = "approved"
	ProductStatusRejected ProductStatus = "rejected"
	ProductStatusOffline  ProductStatus = "offline"
)

type Product struct {
	ID        uint           `gorm:"primaryKey" json:"id"`
	CreatedAt time.Time      `json:"created_at"`
	UpdatedAt time.Time      `json:"updated_at"`
	DeletedAt gorm.DeletedAt `gorm:"index" json:"-"`

	// 基本信息
	NameZh     string        `gorm:"size:200;not null" json:"name_zh"`
	NameEn     string        `gorm:"size:200;not null" json:"name_en"`
	SupplierID uint          `gorm:"index;not null" json:"supplier_id"`
	RegionID   uint          `gorm:"index" json:"region_id"`
	CategoryID uint          `gorm:"index" json:"category_id"`
	Status       ProductStatus `gorm:"size:20;default:draft" json:"status"`
	RejectReason string        `gorm:"size:500" json:"reject_reason,omitempty"`

	// 价格
	PriceFrom float64 `gorm:"type:decimal(10,2)" json:"price_from"`
	Currency  string  `gorm:"size:10;default:AUD" json:"currency"`

	// 双语详情
	SummaryZh     string `gorm:"size:500" json:"summary_zh"`
	SummaryEn     string `gorm:"size:500" json:"summary_en"`
	DescriptionZh string `gorm:"type:text" json:"description_zh"`
	DescriptionEn string `gorm:"type:text" json:"description_en"`
	AddressZh     string `gorm:"size:500" json:"address_zh"`
	AddressEn     string `gorm:"size:500" json:"address_en"`

	// 元数据
	Duration    string `gorm:"size:50" json:"duration"`      // e.g. "3 hours", "Full day"
	GroupSize   string `gorm:"size:50" json:"group_size"`     // e.g. "2-15"
	Tags        string         `gorm:"type:jsonb;default:'[]'" json:"tags"` // JSON array of tag strings
	Metadata    datatypes.JSON `gorm:"type:jsonb;default:'{}'" json:"metadata"`
	IsFeatured  bool           `gorm:"default:false" json:"is_featured"`
	SortOrder   int    `gorm:"default:0" json:"sort_order"`

	// 评分
	Rating      float64 `gorm:"type:decimal(3,2);default:0" json:"rating"`
	ReviewCount int     `gorm:"default:0" json:"review_count"`

	// OCTO / Trip.com Connect
	OctoEnabled  bool       `gorm:"default:false" json:"octo_enabled"`    // 是否上架 Trip.com
	OctoSyncedAt *time.Time `json:"octo_synced_at,omitempty"`             // 最后同步时间

	// REQ-20260509-0004: AI ZH→EN translation provenance.
	// AutoGeneratedEn 标记当前 *_en 字段由 AI 翻译生成；admin 可在列表里优先 review。
	// ManualOverrideEn 由 admin 手工锁定 EN 后置 true，后续 ZH 改动不再触发自动重译。
	AutoGeneratedEn  bool `gorm:"default:false" json:"auto_generated_en"`
	ManualOverrideEn bool `gorm:"default:false" json:"manual_override_en"`

	// REQ-20260509-0015: AI EN→ZH translation provenance (双向对偶 0004).
	// AutoGeneratedZh 标记当前 *_zh 字段由 AI 翻译生成；admin 可在列表里优先 review。
	// ManualOverrideZh 由 admin/supplier 手工锁定 ZH 后置 true，后续 EN 改动不再触发自动重译。
	AutoGeneratedZh  bool `gorm:"default:false" json:"auto_generated_zh"`
	ManualOverrideZh bool `gorm:"default:false" json:"manual_override_zh"`

	// REQ-20260509-0019: 代录身份 — supplier_self（默认）/ admin_proxy。
	// CreatedByAdminID 在 CreatedVia=admin_proxy 时关联到 admin.id；ON DELETE SET NULL
	// 让 admin 离职后历史代录关系优雅降级。supplier 端列表 / 详情据此显示
	// "Created by ${admin.name} on ${created_at}" 提示，避免 supplier 误以为
	// 名下被注入陌生商品。是历史属性、创建时定调、后续 update 不改写。
	CreatedVia       string `gorm:"size:20;default:supplier_self;not null" json:"created_via"`
	CreatedByAdminID *uint  `json:"created_by_admin_id,omitempty"`

	// 关联
	Supplier   *models.Supplier  `gorm:"foreignKey:SupplierID" json:"supplier,omitempty"`
	Region     *Region           `gorm:"foreignKey:RegionID" json:"region,omitempty"`
	Category   *Category         `gorm:"foreignKey:CategoryID" json:"category,omitempty"`
	Images     []ProductImage    `gorm:"foreignKey:ProductID" json:"images,omitempty"`
	Packages   []ProductPackage  `gorm:"foreignKey:ProductID" json:"packages,omitempty"`
	Highlights []ProductHighlight `gorm:"foreignKey:ProductID" json:"highlights,omitempty"`
	FAQs       []ProductFAQ      `gorm:"foreignKey:ProductID" json:"faqs,omitempty"`
	Schedules  []ProductSchedule `gorm:"foreignKey:ProductID" json:"schedules,omitempty"`
}

func (Product) TableName() string {
	return "products"
}
